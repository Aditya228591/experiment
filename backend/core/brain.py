"""Gemini API client wrapper with structured JSON schema support using Pydantic."""

import json
import os
import re
from typing import Optional, Type, TypeVar

from pathlib import Path
from dotenv import load_dotenv, find_dotenv
from google import genai
from google.genai import types
from pydantic import BaseModel

# Search workspace, parent directories, and user home directory for .env
_env_found = find_dotenv(usecwd=True)
if _env_found:
    load_dotenv(_env_found)
load_dotenv(Path.home() / ".env")
load_dotenv()

T = TypeVar("T", bound=BaseModel)

_client: Optional[genai.Client] = None
DEFAULT_MODEL = os.getenv("GEMINI_MODEL", "gemini-3.5-flash-lite")
FALLBACK_MODELS = ["gemini-3.5-flash-lite", "gemini-3.8-flash", "gemini-3.1-flash-lite"]


def is_configured() -> bool:
    """Check if a Gemini API key is available."""
    return bool(os.getenv("GEMINI_API_KEY") or os.getenv("GOOGLE_API_KEY"))


def set_api_key(api_key: str):
    """Dynamically set or override the Gemini API key."""
    global _client
    os.environ["GEMINI_API_KEY"] = api_key.strip()
    _client = None


def get_client() -> genai.Client:
    """Retrieve or initialize the GenAI client.

    Raises:
        RuntimeError: If GEMINI_API_KEY is not set.
    """
    global _client
    if _client is not None:
        return _client

    api_key = os.getenv("GEMINI_API_KEY") or os.getenv("GOOGLE_API_KEY")
    if not api_key:
        raise RuntimeError(
            "GEMINI_API_KEY is not set. Please provide it in your .env file or environment variables."
        )

    _client = genai.Client(api_key=api_key)
    return _client


def _clean_json_text(raw_text: str) -> str:
    """Strip markdown code fence wrappers from raw LLM text if present."""
    text = raw_text.strip()
    match = re.search(r"```(?:json)?\s*([\s\S]*?)\s*```", text)
    if match:
        return match.group(1).strip()
    return text


def generate_structured(
    prompt: str,
    system_instruction: str,
    schema_cls: Type[T],
    model: str = DEFAULT_MODEL,
) -> T:
    """Generate structured output adhering strictly to a Pydantic schema class.

    Args:
        prompt: The user or task prompt.
        system_instruction: Guiding instructions for the model.
        schema_cls: The Pydantic model class defining the response shape.
        model: Model identifier (defaults to gemini-2.5-flash).

    Returns:
        An instance of schema_cls populated with model output.
    """
    client = get_client()
    config = types.GenerateContentConfig(
        system_instruction=system_instruction,
        response_mime_type="application/json",
        response_schema=schema_cls,
        temperature=0.2,
    )

    models_to_try = [model] + [m for m in FALLBACK_MODELS if m != model]

    last_error: Optional[Exception] = None
    for target_model in models_to_try:
        try:
            response = client.models.generate_content(
                model=target_model,
                contents=prompt,
                config=config,
            )

            # Check if parsed directly by the SDK
            if response.parsed is not None:
                if isinstance(response.parsed, schema_cls):
                    return response.parsed
                if isinstance(response.parsed, dict):
                    return schema_cls.model_validate(response.parsed)

            # Fallback to response.text parsing
            if response.text:
                cleaned = _clean_json_text(response.text)
                return schema_cls.model_validate_json(cleaned)

            raise ValueError("Model returned an empty response.")
        except Exception as exc:
            last_error = exc
            # If model name not found or deprecated, try the next model
            err_msg = str(exc).lower()
            if "not found" in err_msg or "unsupported" in err_msg or "404" in err_msg:
                continue
            raise exc

    if last_error:
        raise last_error
    raise RuntimeError("Failed to generate structured content.")


def generate_text(
    prompt: str,
    system_instruction: str,
    model: str = DEFAULT_MODEL,
) -> str:
    """Generate free-form text from Gemini.

    Args:
        prompt: The user or task prompt.
        system_instruction: Guiding instructions for the model.
        model: Model identifier (defaults to gemini-2.5-flash).

    Returns:
        String content generated by the model.
    """
    client = get_client()
    config = types.GenerateContentConfig(
        system_instruction=system_instruction,
        temperature=0.2,
    )

    models_to_try = [model] + [m for m in FALLBACK_MODELS if m != model]

    last_error: Optional[Exception] = None
    for target_model in models_to_try:
        try:
            response = client.models.generate_content(
                model=target_model,
                contents=prompt,
                config=config,
            )
            return response.text or ""
        except Exception as exc:
            last_error = exc
            err_msg = str(exc).lower()
            if "not found" in err_msg or "unsupported" in err_msg or "404" in err_msg:
                continue
            raise exc

    if last_error:
        raise last_error
    raise RuntimeError("Failed to generate text content.")

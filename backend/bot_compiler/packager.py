"""Packager module for exporting self-contained automation bots."""

import re
from pathlib import Path
from typing import List

from core.state import TeacherState


def _sanitize_name(name: str) -> str:
    """Sanitize name string into a valid filesystem folder name."""
    clean = re.sub(r"[^a-zA-Z0-9_\-]", "_", name).strip("_").lower()
    return clean if clean else "automation_bot"


def package_automation(state: TeacherState, base_export_dir: str = "exported_processes", base_output_dir: str = None, **kwargs) -> Path:
    """Package verified automation into a standalone, deployable folder.

    Creates:
      - bot.py: The standalone automation code.
      - requirements.txt: Tailored minimal pip dependencies.
      - .env.example: Secret templates for the user to fill in.
      - README.md: Clear instructions for deployment and testing.

    Args:
        state: The TeacherState containing verified draft_code and spec.
        base_export_dir: The root export folder (defaults to 'exported_processes').
        base_output_dir: Alias for base_export_dir.

    Returns:
        Path to the exported bot folder.
    """
    if base_output_dir:
        base_export_dir = base_output_dir

    spec = state.spec
    if not spec:
        raise ValueError("Cannot package automation: ProcessSpec is missing from state.")

    folder_name = _sanitize_name(spec.name)
    export_dir = Path(base_export_dir) / folder_name
    export_dir.mkdir(parents=True, exist_ok=True)

    # 1. Write bot.py
    bot_file = export_dir / "bot.py"
    with open(bot_file, "w", encoding="utf-8") as f:
        f.write(state.draft_code)

    # 2. Write requirements.txt
    deps: List[str] = state.dependencies or ["python-dotenv"]
    req_file = export_dir / "requirements.txt"
    with open(req_file, "w", encoding="utf-8") as f:
        for dep in sorted(set(deps)):
            f.write(f"{dep}\n")

    # 3. Write .env.example
    env_example_file = export_dir / ".env.example"
    with open(env_example_file, "w", encoding="utf-8") as f:
        f.write("# Environment Configuration & Credentials\n")
        f.write("# Copy this file to .env and insert your real credentials\n\n")
        secrets = spec.required_secrets or ["SECRET_KEY"]
        for secret in secrets:
            key_clean = secret.strip().upper()
            f.write(f"{key_clean}=your_{key_clean.lower()}_here\n")

    # 4. Write README.md
    steps_markdown = "\n".join(f"{i+1}. {step}" for i, step in enumerate(spec.processing_steps))
    readme_file = export_dir / "README.md"
    readme_content = f"""# {spec.name.replace('_', ' ').title()}

Generated by **Teacher AI** — Standalone Automated Bot.

## Overview
- **Trigger Type:** `{spec.trigger_type}`
- **Schedule:** `{spec.schedule}`
- **Delivery Channel:** `{spec.delivery_channel}`

### Execution Steps
{steps_markdown}

---

## Quickstart Setup

### 1. Install Dependencies
Ensure you have Python 3.9+ installed, then install the dependencies:
```bash
pip install -r requirements.txt
```

### 2. Configure Environment Variables
Copy `.env.example` to `.env`:
```bash
cp .env.example .env
```
Open `.env` and fill in your real credentials:
```env
{chr(10).join(f"{s.strip().upper()}=..." for s in spec.required_secrets)}
```

---

## Running the Bot

### Simulated Dry-Run (Safe Test Mode)
Verify the bot without making real network calls or sending real notifications:
```bash
python bot.py --dry-run
```

### Single Execution Test
Execute the automation once immediately:
```bash
python bot.py --run-once
```

### Continuous Background Scheduler
Run the bot according to its configured schedule (`{spec.schedule}`):
```bash
python bot.py
```
*(Press `Ctrl+C` to stop the scheduler).*

---
*Packaged cleanly by Teacher AI. Ready for deployment on any computer or server.*
"""
    with open(readme_file, "w", encoding="utf-8") as f:
        f.write(readme_content)

    return export_dir.resolve()
